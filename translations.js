function setLanguage(lang) {
    localStorage.setItem('selectedLang', lang);

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    const dict = translations[lang];
    if (!dict) return;

    // Direct data attribute support (data-ru, data-tk)
    document.querySelectorAll('[data-ru], [data-tk]').forEach(el => {
        const text = el.getAttribute(`data-${lang}`);
        if (text) el.innerHTML = text;
    });

    // Placeholders translation
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
        if (!el._originalPlaceholder) el._originalPlaceholder = el.placeholder.trim();
        const origKey = el._originalPlaceholder;
        if (dict[origKey]) el.placeholder = dict[origKey];
    });

    // Normalize helper to survive HTML whitespace differences
    const clean = str => str ? str.replace(/\s+/g, ' ').trim() : '';

    // Create a normalized lookup map from your existing dictionary
    const normalizedDict = {};
    Object.keys(dict).forEach(key => {
        normalizedDict[clean(key)] = dict[key];
    });

    // Translate block elements (Bot answers, chat messages, lists, paragraphs)
    document.querySelectorAll('.chat-message, .bot-message, .user-message, .knowledge-item, p, span, h1, h2, h3, h4, li').forEach(el => {
        // Save original HTML on first read
        if (!el._originalHTML) {
            el._originalHTML = el.innerHTML;
        }

        const key = clean(el._originalHTML);

        if (normalizedDict[key]) {
            el.innerHTML = normalizedDict[key];
            el.setAttribute('data-translated', 'true'); // Tag so text node crawler skips it
        }
    });

    // Translate standalone text nodes (skips elements already translated as HTML blocks)
    function translateTextNodes(node) {
        if (node.nodeType === Node.ELEMENT_NODE) {
            // Skip script/style and blocks already translated above
            if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE' || node.getAttribute('data-translated') === 'true') {
                return;
            }
            Array.from(node.childNodes).forEach(translateTextNodes);
        } else if (node.nodeType === Node.TEXT_NODE) {
            const rawText = clean(node.nodeValue);

            if (rawText.length > 0) {
                if (!node._originalText) {
                    node._originalText = rawText;
                }

                const origKey = node._originalText;

                if (normalizedDict[origKey]) {
                    const leadingSpaces = node.nodeValue.match(/^\s*/)[0];
                    const trailingSpaces = node.nodeValue.match(/\s*$/)[0];
                    node.nodeValue = leadingSpaces + normalizedDict[origKey] + trailingSpaces;
                }
            }
        }
    }

    translateTextNodes(document.body);
}

// Modal dialog functionality fix
function openAuthModal() {
    const modal = document.getElementById('authModal');
    if (modal) modal.style.display = 'flex';
}

function closeAuthModal() {
    const modal = document.getElementById('authModal');
    if (modal) modal.style.display = 'none';
}

function switchTab(type) {
    const loginTab = document.getElementById('loginTab');
    const regTab = document.getElementById('regTab');
    const submitBtn = document.getElementById('authSubmitBtn');
    const lang = localStorage.getItem('selectedLang') || 'ru';

    if (type === 'login') {
        loginTab?.classList.add('active');
        regTab?.classList.remove('active');
        if (submitBtn) submitBtn.textContent = translations[lang]["Войти"] || "Войти";
    } else {
        regTab?.classList.add('active');
        loginTab?.classList.remove('active');
        if (submitBtn) submitBtn.textContent = translations[lang]["Регистрация"] || "Регистрация";
    }
}


window.onclick = function(event) {
    const modal = document.getElementById('authModal');
    if (event.target === modal) {
        closeAuthModal();
    }
};

document.addEventListener('DOMContentLoaded', () => {
    const currentLang = localStorage.getItem('selectedLang') || 'ru';
    setLanguage(currentLang);
});
